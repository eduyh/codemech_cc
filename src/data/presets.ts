export function createEmptySubroutines(): MechSubroutine[] {
  return MECH_SUBROUTINE_SLOT_SPECS.map((spec) => ({
    slotId: spec.slotId,
    name: spec.defaultName,
    gridSize: spec.gridSize,
    cells: [{ row: 0, col: 0, op: 'start', dir: 'E' }],
  }));
}

